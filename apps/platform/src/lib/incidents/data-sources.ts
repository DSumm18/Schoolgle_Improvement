/**
 * Incident Data Sources
 *
 * Defines where incident data originates and where it is sent.
 * Used by the incident module for form pre-population, validation,
 * and by Ed to explain data provenance.
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type DataSourceType = "internal" | "external" | "mis";
export type DataSourceDirection = "source" | "destination" | "both";

export interface DataSource {
  /** Human-readable name */
  name: string;
  /** Whether the source is internal to Schoolgle, an external system, or a MIS */
  type: DataSourceType;
  /** Whether data flows into the incident module, out of it, or both */
  direction: DataSourceDirection;
  /** Specific data fields exchanged */
  fields: string[];
  /** Description for Ed and documentation */
  description: string;
}

