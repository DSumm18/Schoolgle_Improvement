// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

/** Return all sources (data flowing into the incident module) */
export function getSourceSystems(): DataSource[] {
  return INCIDENT_DATA_SOURCES.filter(
    (ds) => ds.direction === "source" || ds.direction === "both",
  );
}

/** Return all destinations (data flowing out of the incident module) */
export function getDestinationSystems(): DataSource[] {
  return INCIDENT_DATA_SOURCES.filter(
    (ds) => ds.direction === "destination" || ds.direction === "both",
  );
}

/** Return data sources by type */
export function getDataSourcesByType(type: DataSourceType): DataSource[] {
  return INCIDENT_DATA_SOURCES.filter((ds) => ds.type === type);
}

/** Return all fields that flow into the incident module (useful for form pre-population) */
export function getAllSourceFields(): string[] {
  return Array.from(new Set(getSourceSystems().flatMap((ds) => ds.fields)));
}
